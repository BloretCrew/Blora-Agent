//! Embeds the vendored Blora Design assets so the Web UI ships complete in the
//! binary. Reading them from disk at run time tied the UI to a build-machine
//! path (`blora-design/`, which is gitignored) and left released binaries with
//! no stylesheet at all.

use std::path::{Path, PathBuf};

fn main() {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../web/vendor/design");
    println!("cargo:rerun-if-changed={}", root.display());
    let mut assets = Vec::new();
    collect(&root, &root, &mut assets);
    assets.sort_by(|a, b| a.0.cmp(&b.0));
    if assets.is_empty() {
        // Fail loudly instead of emitting a UI with no styles.
        panic!(
            "web/vendor/design is missing or empty; the Web UI would ship unstyled. \
             Restore the vendored Blora Design assets before building."
        );
    }

    let mut generated = String::from(
        "// @generated by build.rs from web/vendor/design. Do not edit.\n\
         pub(super) static VENDOR_ASSETS: &[(&str, &str)] = &[\n",
    );
    for (relative, absolute) in &assets {
        generated.push_str(&format!(
            "    ({relative:?}, include_str!({absolute:?})),\n"
        ));
    }
    generated.push_str("];\n");

    let out = PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR")).join("vendor_assets.rs");
    std::fs::write(out, generated).expect("write vendor asset table");
}

fn collect(root: &Path, dir: &Path, out: &mut Vec<(String, String)>) {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect(root, &path, out);
            continue;
        }
        let Some(extension) = path.extension().and_then(|value| value.to_str()) else {
            continue;
        };
        // The server only ever serves stylesheets and scripts.
        if !matches!(extension, "css" | "js") {
            continue;
        }
        let Ok(relative) = path.strip_prefix(root) else {
            continue;
        };
        let Some(relative) = relative.to_str() else {
            continue;
        };
        let absolute = path.to_string_lossy().into_owned();
        out.push((relative.replace('\\', "/"), absolute));
    }
}
